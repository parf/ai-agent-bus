#!/usr/bin/env python3
"""The bundled agents' one-line list in docs/agents/README.md (RT32).

Each line is the agent's linked name and the description its help prints:
agent.json's `description`, or display.BusDescription for the daemon's #bus.
`--write` regenerates the block between the markers; agent_docs_test.py checks it.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
AGENTS = ROOT / 'src' / 'agents'
INDEX = ROOT / 'docs' / 'agents' / 'README.md'
BEGIN = '<!-- bundled-agents: generated by src/agents/agent_docs.py --write -->'
END = '<!-- /bundled-agents -->'

# Agents whose owners have not yet added the `docs` key or the page structure.
# Each names its page and why; the check fails once an entry is no longer needed.
PENDING = {
}


def go_const(name):
    """A string constant from internal/display; refuse loudly when it is missing."""
    text = ''.join(p.read_text() for p in sorted((ROOT / 'src/internal/display').glob('*.go')) if not p.name.endswith('_test.go'))
    found = re.findall(r'(?m)^const ' + name + r' = (?:([A-Z][A-Za-z]*) \+ )?"([^"\\]*)"$', text)
    if len(found) != 1:
        raise SystemExit(f'agent_docs: display.{name} not found exactly once')
    prefix, value = found[0]
    return (go_const(prefix) if prefix else '') + value


def manifests():
    """Every bundled agent.json, keyed by its template name."""
    found = {}
    for path in sorted(AGENTS.glob('**/agent.json')):
        if 'node_modules' in path.parts:
            continue
        name = path.parent.name
        if name in found:
            raise SystemExit(f'agent_docs: two agents named {name}')
        found[name] = (path, json.loads(path.read_text()))
    return found


def agents():
    """(name, page, description, docs URL or None) for every bundled agent and #bus."""
    rows = [('bus', 'bus.md', go_const('BusDescription'), go_const('BusDocs'))]
    for name, (_, manifest) in manifests().items():
        docs = manifest.get('docs')
        page = docs.rsplit('/', 1)[-1] if docs else PENDING.get(name, (name + '.md',))[0]
        rows.append((name, page, manifest['description'], docs))
    return sorted(rows)


def render():
    # A backslash keeps Markdown from reading <to> as an HTML tag.
    lines = [f'- [`#{name}`]({page}) — ' + description.replace('<', '\\<') for name, page, description, _ in agents()]
    return BEGIN + '\n' + '\n'.join(lines) + '\n' + END


def block(text):
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise SystemExit('agent_docs: the bundled-agents markers must appear once each, in order')
    start = text.index(BEGIN)
    return start, text.index(END) + len(END)


def main(argv):
    if not argv:
        print(render())
        return 0
    if argv != ['--write']:
        raise SystemExit('usage: agent_docs.py [--write]')
    text = INDEX.read_text()
    start, end = block(text)
    fresh = text[:start] + render() + text[end:]
    if fresh != text:
        INDEX.write_text(fresh)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
