fn main() {
    let canonical = std::path::Path::new("../../internal/version/VERSION");
    let generated = std::path::Path::new("VERSION.local");
    let source = if canonical.exists() {
        canonical
    } else {
        generated
    };
    println!("cargo:rerun-if-changed={}", canonical.display());
    println!("cargo:rerun-if-changed={}", generated.display());
    let version = std::fs::read_to_string(source)
        .expect("canonical VERSION or metadata generated by package.sh is required");
    println!("cargo:rustc-env=AGENT_BUS_VERSION={}", version.trim());
}
